#!/usr/bin/env node
// Mirror the Kalaris Labs blog index into blog/index.mdx.
//
// Reads https://kalarislabs.com/blog, then each post's og:image (the poster graphic), downloads the posters
// to images/blog/<slug>.jpg and writes one card per post. The full articles stay on kalarislabs.com, which is
// the canonical source, so the docs do not compete with them as duplicate content.
//
// Usage: node scripts/sync_blog.mjs        (run from the repository root, Node 18 or later)

import { mkdir, readdir, rm, writeFile } from "node:fs/promises";

const SITE = "https://kalarislabs.com";
const IMG_DIR = "images/blog";
const MONTH = /^(January|February|March|April|May|June|July|August|September|October|November|December) \d+, \d{4}$/;

const decode = (s) =>
  s.replace(/&amp;/g, "&").replace(/&#39;|&#x27;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">");
const attr = (s) => s.replace(/"/g, "&quot;").replace(/</g, "&lt;");
const text = (s) => s.replace(/</g, "&lt;").replace(/{/g, "&#123;").replace(/}/g, "&#125;");
const cell = (s) => s.replace(/\|/g, "\\|");

async function get(url) {
  const res = await fetch(url, { headers: { "user-agent": "kalarislabs-docs-sync" } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res;
}

function parseListing(html) {
  const posts = [];
  const seen = new Set();
  for (const m of html.matchAll(/<a[^>]+href="\/blog\/([a-z0-9-]+)"[^>]*>([\s\S]*?)<\/a>/g)) {
    const [, slug, body] = m;
    if (seen.has(slug)) continue;
    seen.add(slug);
    const title = decode((body.match(/<h[23][^>]*>([\s\S]*?)<\/h[23]>/) || [])[1] || "").replace(/<[^>]+>/g, "").trim();
    const parts = body.replace(/<[^>]+>/g, "|").split("|").map((s) => decode(s.trim())).filter(Boolean);
    const di = parts.findIndex((p) => MONTH.test(p));
    const ti = parts.indexOf(title);
    const by = parts.find((p) => p.startsWith("By "));
    posts.push({
      slug,
      title,
      date: parts[di] || "",
      topic: di > 0 && parts[0] !== "·" ? parts[0] : "",
      description: parts[ti + 1] || "",
      author: by ? by.slice(3) : parts[ti + 2] || "Kalaris Labs",
      readTime: parts.find((p) => p.endsWith("min read")) || "",
    });
  }
  return posts;
}

async function poster(slug) {
  const html = await (await get(`${SITE}/blog/${slug}`)).text();
  const og = (html.match(/<meta property="og:image" content="([^"]+)"/) || [])[1];
  if (!og) throw new Error(`no og:image on ${slug}`);
  const buf = Buffer.from(await (await get(decode(og))).arrayBuffer());
  await writeFile(`${IMG_DIR}/${slug}.jpg`, buf);
}

function render(posts) {
  const cards = posts
    .map(
      (p) => `  <Card title="${attr(p.title)}" img="/${IMG_DIR}/${p.slug}.jpg" href="${SITE}/blog/${p.slug}">
    ${[p.topic, p.date, p.readTime, p.author].filter(Boolean).join(" · ")}

    ${text(p.description)}
  </Card>`,
    )
    .join("\n");
  const rows = posts
    .map((p) => `| [${cell(p.title)}](${SITE}/blog/${p.slug}) | ${p.topic || "general"} | ${p.date} | ${p.author} |`)
    .join("\n");
  return `---
title: "Kalaris Labs blog: agent engineering, evaluation and AI research essays"
sidebarTitle: "Blog"
description: "All ${posts.length} Kalaris Labs blog posts: close reads of agent harnesses, speculative decoding, 1-bit quantization, agent security, agentic commerce and neuroscience, with their poster graphics and links to the full articles."
keywords: ["Kalaris Labs blog", "AI agent engineering blog", "agent harnesses", "LLM quantization", "speculative decoding", "agent security", "agentic commerce", "Sayan Chowdhury"]
"og:image": "https://docs.kalarislabs.com/images/blog-og.jpg"
boost: 2
---

{/* Generated by scripts/sync_blog.mjs. Edit the script, not this file. */}

**Engineering deep-dives and research essays from Kalaris Labs.** Every post links to the full article on
[kalarislabs.com/blog](${SITE}/blog), which is the canonical version. Posts are newest first. The lab's papers
are on the [research page](/research).

<Columns cols={2}>
${cards}
</Columns>

## All posts as a table

| Post | Topic | Date | Author |
|---|---|---|---|
${rows}

Questions about the lab? See the [FAQ](/lab/faq), [about the lab](/lab/about) or the [founder](/lab/sayan-chowdhury).
`;
}

const posts = parseListing(await (await get(`${SITE}/blog`)).text());
if (posts.length === 0) throw new Error("no posts found on the blog listing");
const bad = posts.filter((p) => !p.title || !p.date || !p.description);
if (bad.length) throw new Error(`could not parse: ${bad.map((p) => p.slug).join(", ")}`);

await mkdir(IMG_DIR, { recursive: true });
const keep = new Set(posts.map((p) => `${p.slug}.jpg`));
for (const f of await readdir(IMG_DIR)) if (!keep.has(f)) await rm(`${IMG_DIR}/${f}`);
for (let i = 0; i < posts.length; i += 8) await Promise.all(posts.slice(i, i + 8).map((p) => poster(p.slug)));

await mkdir("blog", { recursive: true });
await writeFile("blog/index.mdx", render(posts));
console.log(`blog/index.mdx: ${posts.length} posts, posters in ${IMG_DIR}/`);
